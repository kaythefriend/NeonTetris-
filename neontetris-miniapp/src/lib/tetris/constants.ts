// Gravity speed (ms per row drop) per level, gentle-ish curve for mobile play.
export const LEVEL_SPEED_MS: number[] = [
  800, 720, 630, 550, 470, 380, 300, 230, 170, 120, 100, 90, 80, 70, 60,
];

export function speedForLevel(level: number): number {
  const idx = Math.min(level - 1, LEVEL_SPEED_MS.length - 1);
  return LEVEL_SPEED_MS[Math.max(idx, 0)];
}

